// Scratch: screenshots of the projects home for the M14.3 thread (not committed).
import { readFileSync } from "node:fs";
import { chromium } from "@playwright/test";

const BASE = process.env.BASE ?? "http://localhost:5173";
const OUT = process.env.OUT ?? "/tmp/claude-0/shots";
const MODEL = process.env.MODEL;
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto(`${BASE}/app`);
await page.getByLabel("Login").fill("alice");
await page.getByLabel("Password").fill("alice-local");
await page.getByRole("button", { name: "Sign in" }).click();
await page.getByRole("navigation", { name: "Home sections" }).waitFor();
const api = page.request;
const post = async (path, data) => (await (await api.post(`${BASE}${path}`, { data })).json());
const pumps = (await post("/api/folders", { name: "Pump housings" })).folder;
const brackets = (await post("/api/folders", { name: "Brackets" })).folder;
await post("/api/folders", { name: "Impellers", parentId: pumps.id });
await post("/api/projects", { name: "Housing rev B", folderId: pumps.id });
await post("/api/projects", { name: "Seal plate", folderId: pumps.id });
await post("/api/projects", { name: "L-bracket 6 mm", folderId: brackets.id });
const old = (await post("/api/projects", { name: "Old trial" })).project;
await api.post(`${BASE}/api/projects/${old.id}/trash`);
const scrap = (await post("/api/folders", { name: "Scrap" })).folder;
await post("/api/projects", { name: "Scrap idea", folderId: scrap.id });
await api.post(`${BASE}/api/folders/${scrap.id}/trash`);

// A project with a geometry, whose thumbnail the workbench draws.
await page.reload();
await page.getByRole("main").getByRole("button", { name: "New project" }).click();
await page.getByLabel("Project name").fill("Block 40 x 20 x 10");
await page.getByRole("button", { name: "Create and open" }).click();
await page.getByRole("region", { name: "Geometry", exact: true }).locator('input[type="file"]').setInputFiles({ name: "block.step", mimeType: "application/step", buffer: readFileSync(MODEL) });
await page.getByRole("button", { name: "Confirm unit" }).click({ timeout: 180_000 });
await page.getByText("40 × 20 × 10 mm").waitFor();
await page.waitForResponse((r) => r.url().includes("/thumbnail") && r.request().method() === "PUT", { timeout: 60_000 }).catch(() => {});
await page.screenshot({ path: `${OUT}/workbench-header.png` });
await page.getByRole("banner").getByRole("button", { name: "Projects" }).click();
await page.getByRole("navigation", { name: "Home sections" }).waitFor();
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/home-recent.png` });
await page.getByRole("navigation", { name: "Home sections" }).getByRole("button", { name: "My projects" }).click();
await page.getByRole("main").getByRole("button", { name: /^Block 40/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/home-my-projects-details.png` });
await page.getByRole("navigation", { name: "Home sections" }).getByRole("button", { name: "Pump housings" }).click();
await page.getByRole("main").getByRole("button", { name: "List" }).click();
await page.screenshot({ path: `${OUT}/home-folder-list.png` });
await page.getByRole("main").getByRole("button", { name: "Grid" }).click();
await page.getByLabel("Search projects and folders").fill("plate");
await page.screenshot({ path: `${OUT}/home-search.png` });
await page.getByLabel("Search projects and folders").fill("");
await page.getByRole("navigation", { name: "Home sections" }).getByRole("button", { name: "Trash" }).click();
await page.getByRole("main").getByRole("button", { name: /^Scrap/ }).click();
await page.screenshot({ path: `${OUT}/home-trash.png` });
await page.getByRole("button", { name: "Light theme" }).or(page.getByRole("button", { name: "Dark theme" })).first().click();
await page.getByRole("navigation", { name: "Home sections" }).getByRole("button", { name: "My projects" }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/home-dark.png` });
await browser.close();
